export function filterItemsByRank(items, category, maxRank) {
  const rankTable = itemRanks[category];

  if (!Array.isArray(items) || !rankTable) {
    return [];
  }

  return items.filter((item) => {
    const name =
      typeof item === "string"
        ? item
        : item?.name;

    const itemRank = rankTable[name];

    return (
      Number.isInteger(itemRank) &&
      itemRank <= Number(maxRank)
    );
  });
}
